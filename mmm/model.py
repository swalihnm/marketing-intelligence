"""Bayesian marketing mix model, built in PyMC.

revenue_t = intercept + trend_t + seasonality_t + price_effect_t
          + sum_c beta_c * hill(adstock(spend_c,t, alpha_c), s_c, k_c)
          + epsilon_t

This mirrors simulate/dgp.py's functional form on purpose: the recovery
study (simulate/recovery_study.py) fits this model to data generated by the
DGP and checks whether the posterior recovers the DGP's true parameters.
`mmm/priors.py` supplies channel priors independently of the DGP's true
values (see its docstring) so the recovery test isn't circular.
"""
from __future__ import annotations

import numpy as np
import pymc as pm
import pytensor.tensor as pt

from mmm.priors import DECAY_BETA_PRIOR, default_channel_prior
from transforms.adstock import geometric_adstock_pt
from transforms.saturation import hill


def build_mmm(
    df, channels: list[str], max_lag: int = 8, price_col: str = "price",
    extra_covariates: dict[str, np.ndarray] | None = None,
) -> pm.Model:
    """`extra_covariates` is an optional, backward-compatible extension
    (added in Phase 8, for fitting on ingest/build_tier2_panel.py's real
    Tier 3 covariates alongside the Tier 2 reference spine): a dict of
    {name: raw series}. Each gets its own standardized linear term
    (coefficient = revenue change per 1-std-dev move in the covariate) —
    standardizing keeps the coefficients comparably scaled and the
    sampler well-conditioned regardless of each covariate's raw units
    (an index, a percentage, degrees Celsius, etc). Omitting this
    parameter (the default) reproduces the exact model used throughout
    Phases 1-6 on simulated data — nothing about the existing recovery
    study or allocator changes."""
    T = len(df)
    t = df["t"].values.astype(float)
    revenue = df["revenue"].values.astype(float)
    price = df[price_col].values.astype(float)
    price_baseline = float(price.mean())

    spend = {c: df[f"spend_{c}"].values.astype(float) for c in channels}
    mean_spend = {c: float(spend[c].mean()) for c in channels}

    channel_priors = {c: default_channel_prior(c, mean_spend[c]) for c in channels}
    decay_a = np.array([DECAY_BETA_PRIOR[channel_priors[c].decay_belief][0] for c in channels])
    decay_b = np.array([DECAY_BETA_PRIOR[channel_priors[c].decay_belief][1] for c in channels])
    beta_sigma = np.array([channel_priors[c].beta_sigma for c in channels])
    hill_k_sigma = np.array([channel_priors[c].hill_k_sigma for c in channels])

    coords = {"channel": channels, "obs_id": np.arange(T)}

    with pm.Model(coords=coords) as model:
        t_data = pm.Data("t", t, dims="obs_id")
        price_data = pm.Data("price", price, dims="obs_id")
        spend_data = {c: pm.Data(f"spend_{c}", spend[c], dims="obs_id") for c in channels}

        intercept = pm.Normal("intercept", mu=float(revenue.mean()), sigma=float(revenue.std()) * 2)
        trend_coef = pm.Normal("trend_coef", mu=0, sigma=500)
        a1 = pm.Normal("season_a1", 0, 5e4)
        b1 = pm.Normal("season_b1", 0, 5e4)
        a2 = pm.Normal("season_a2", 0, 2e4)
        b2 = pm.Normal("season_b2", 0, 2e4)
        price_coef = pm.Normal("price_coef", 0, 3e4)

        # beta positive-constrained: spend cannot reduce revenue.
        beta = pm.HalfNormal("beta", sigma=beta_sigma, dims="channel")
        # informative decay priors by channel archetype (see mmm/priors.py).
        alpha = pm.Beta("alpha", alpha=decay_a, beta=decay_b, dims="channel")
        hill_s = pm.Gamma("hill_s", alpha=2.0, beta=1.0, dims="channel")
        hill_k = pm.HalfNormal("hill_k", sigma=hill_k_sigma, dims="channel")

        season = (
            a1 * pt.sin(2 * np.pi * t_data / 52)
            + b1 * pt.cos(2 * np.pi * t_data / 52)
            + a2 * pt.sin(4 * np.pi * t_data / 52)
            + b2 * pt.cos(4 * np.pi * t_data / 52)
        )

        contributions = []
        for i, c in enumerate(channels):
            adstocked = geometric_adstock_pt(spend_data[c], alpha[i], max_lag=max_lag)
            saturated = hill(adstocked, hill_s[i], hill_k[i])
            contributions.append(beta[i] * saturated)
        channel_effect = pt.sum(pt.stack(contributions, axis=0), axis=0)

        extra_effect = 0.0
        if extra_covariates:
            for name, series in extra_covariates.items():
                series = np.asarray(series, dtype=float)
                standardized = (series - series.mean()) / series.std()
                cov_data = pm.Data(f"covariate_{name}", standardized, dims="obs_id")
                coef = pm.Normal(f"coef_{name}", mu=0, sigma=float(revenue.std()))
                extra_effect = extra_effect + coef * cov_data

        mu = (
            intercept
            + trend_coef * t_data
            + season
            + price_coef * (price_data - price_baseline)
            + channel_effect
            + extra_effect
        )
        pm.Deterministic("mu", mu, dims="obs_id")

        sigma = pm.HalfNormal("sigma", sigma=float(revenue.std()))
        pm.Normal("revenue_obs", mu=mu, sigma=sigma, observed=revenue, dims="obs_id")

    return model


def fit_mmm(
    model: pm.Model,
    draws: int = 1000,
    tune: int = 1000,
    chains: int = 4,
    cores: int = 1,
    target_accept: float = 0.9,
    random_seed: int = 2024,
    progressbar: bool = False,
):
    with model:
        idata = pm.sample(
            draws=draws,
            tune=tune,
            chains=chains,
            cores=cores,
            target_accept=target_accept,
            random_seed=random_seed,
            progressbar=progressbar,
        )
        idata = pm.sample_posterior_predictive(idata, progressbar=progressbar, extend_inferencedata=True)
    return idata


def sample_prior_predictive(model: pm.Model, samples: int = 500, random_seed: int = 2024):
    with model:
        return pm.sample_prior_predictive(draws=samples, random_seed=random_seed)
